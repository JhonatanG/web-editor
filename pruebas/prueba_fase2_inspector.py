"""Fase 2: inspector adaptable.
Comprueba en Chrome: ancho real del lienzo, ancho exacto y arrastrando el borde,
rango de estilos separado del ancho, valores locales / heredados / del diseño,
restablecer, columnas por rango, que un ajuste de móvil no toca escritorio,
que se conservan las reglas existentes, deshacer, guardar y paneles plegables."""
import re, sys
from playwright.sync_api import sync_playwright
from comun import Editor, check, resumen

with sync_playwright() as p:
    b = p.chromium.launch(channel='chrome')
    ctx = b.new_context(viewport={'width': 1600, 'height': 950})
    ed = Editor(ctx)
    pg, E, V = ed.pg, ed.E, ed.V
    ed.empezar_de_cero()
    for s in ('s-nav', 's-hero-img', 'sec-servicios-iconos'):
        pg.click(f'.sec-card[data-sec="{s}"] .sec-ins'); pg.wait_for_timeout(300); E("editor.select(null)")
    H1 = "tagDe(c) === 'h1'"
    ancho = lambda: E("editor.Canvas.getWindow().innerWidth")
    fila = lambda p: V(f"const f = document.querySelector('#adapt-box [data-fila=\"{p}\"]'); return f ? f.className.replace('ad-fila ', '') : null")
    tam = lambda: E(f"getComputedStyle({ed.comp(H1)}.getEl()).fontSize")

    print('1. Ancho de la vista')
    check('en Escritorio el lienzo mide 1280 px reales y el campo lo muestra', ancho() == 1280 and pg.input_value('#ancho-lienzo') == '1280', [ancho(), pg.input_value('#ancho-lienzo')])
    pg.fill('#ancho-lienzo', '820'); pg.press('#ancho-lienzo', 'Enter'); pg.wait_for_timeout(700)
    check('escribir 820 deja el lienzo en 820 px reales', ancho() == 820, ancho())
    check('el rango automático pasa a Tablet', 'Tablet' in pg.inner_text('#rango-txt'), pg.inner_text('#rango-txt'))
    check('ningún botón de dispositivo queda marcado', E("document.querySelectorAll('[data-device].active').length") == 0)
    bb = pg.locator('.lienzo-asa').bounding_box()
    borde = V("return editor.Canvas.getFrameEl().getBoundingClientRect().right")
    check('el asa está en el borde derecho del lienzo', bb is not None and abs(bb['x'] + bb['width'] / 2 - borde) < 12, [bb, borde])
    pg.mouse.move(bb['x'] + 7, bb['y'] + bb['height'] / 2); pg.mouse.down()
    for i in range(1, 11):
        pg.mouse.move(bb['x'] + 7 - 13 * i, bb['y'] + bb['height'] / 2); pg.wait_for_timeout(30)
    pg.mouse.up(); pg.wait_for_timeout(700)
    w = ancho()
    check('arrastrar el borde hacia la izquierda estrecha la vista', 520 <= w <= 800, w)
    check('el campo muestra el nuevo ancho', pg.input_value('#ancho-lienzo') == str(w), [pg.input_value('#ancho-lienzo'), w])
    pg.focus('.lienzo-asa'); pg.keyboard.press('ArrowRight'); pg.wait_for_timeout(500)
    check('el asa también se mueve con el teclado (+10 px)', ancho() == w + 10, [w, ancho()])
    pg.fill('#ancho-lienzo', '500'); pg.press('#ancho-lienzo', 'Enter'); pg.wait_for_timeout(600)
    check('a 500 px el rango pasa a Móvil', 'Móvil' in pg.inner_text('#rango-txt'))

    print('2. Rango fijado distinto del ancho')
    pg.fill('#ancho-lienzo', '820'); pg.press('#ancho-lienzo', 'Enter'); pg.wait_for_timeout(500)
    pg.click('#rango-estilos'); pg.click('#rango-menu [data-r="movil"]'); pg.wait_for_timeout(600)
    check('se puede ver a 820 px editando los estilos de Móvil', ancho() == 820 and 'Móvil' in pg.inner_text('#rango-txt'), [ancho(), pg.inner_text('#rango-txt')])
    ed.sel(H1)
    pg.click('[data-tab=style]'); pg.wait_for_timeout(200)
    txt = pg.inner_text('#adapt-box')
    check('el inspector distingue vista y rango, y avisa', 'Vista: 820 px' in txt and 'más ancha que el rango' in txt, txt[:200])
    pg.click('#rango-estilos'); pg.click('#rango-menu [data-r=""]'); pg.wait_for_timeout(300)

    print('3. Ajustar el hero solo para móvil')
    reglas_antes = E("editor.Css.getRules().length")
    css_antes = E("editor.getCss()")
    pg.click('[data-device=desktop]'); pg.wait_for_timeout(600)
    ed.sel(H1)
    tam_esc = tam()
    pg.click('[data-device=mobile]'); pg.wait_for_timeout(700)
    ed.sel(H1); pg.click('[data-tab=style]')
    check('sin ajustes, el tamaño de letra figura «del diseño»', fila('font-size') == 'diseno', fila('font-size'))
    pg.fill('#ad-font-size', '30'); pg.press('#ad-font-size', 'Enter'); pg.wait_for_timeout(500)
    check('en Móvil el título mide 30 px', tam() == '30px', tam())
    check('y figura como ajuste local de Móvil', fila('font-size') == 'local', fila('font-size'))
    css = E("editor.getCss()")
    check('la regla se guarda dentro de @media (max-width: 575px)', bool(re.search(r'@media \(max-width: 575px\)\{[^}]*font-size:30px', css)), css[-250:])
    pg.click('[data-device=desktop]'); pg.wait_for_timeout(700)
    ed.sel(H1)
    check('en Escritorio el título no cambia', tam() == tam_esc, [tam_esc, tam()])
    check('ni hay regla de escritorio para el título', E(f"!editor.Css.getRule('#' + {ed.comp(H1)}.getId()) || !editor.Css.getRule('#' + {ed.comp(H1)}.getId()).getStyle()['font-size']"))
    check('el panel lo muestra «del diseño» en Escritorio', fila('font-size') == 'diseno', fila('font-size'))
    pg.fill('#ad-margin-bottom', '40'); pg.press('#ad-margin-bottom', 'Enter'); pg.wait_for_timeout(400)
    pg.click('[data-device=mobile]'); pg.wait_for_timeout(700); ed.sel(H1)
    check('un margen puesto en Escritorio figura como heredado en Móvil', fila('margin-bottom') == 'heredado' and 'Escritorio' in pg.inner_text('#adapt-box [data-fila="margin-bottom"]'), fila('margin-bottom'))
    pg.click('[data-device=tablet]'); pg.wait_for_timeout(700); ed.sel(H1)
    check('en Tablet el tamaño de móvil no aplica («del diseño»)', fila('font-size') == 'diseno', fila('font-size'))
    pg.click('[data-device=mobile]'); pg.wait_for_timeout(700); ed.sel(H1)
    pg.fill('#ad-letter-spacing', '2'); pg.press('#ad-letter-spacing', 'Enter'); pg.wait_for_timeout(400)
    check('un segundo ajuste también es local', fila('letter-spacing') == 'local')
    pg.click('#btn-undo'); pg.wait_for_timeout(500); ed.sel(H1)
    check('deshacer quita el último ajuste adaptable', fila('letter-spacing') == 'diseno' and fila('font-size') == 'local', [fila('letter-spacing'), fila('font-size')])
    pg.click('#adapt-box [data-reset="font-size"]'); pg.wait_for_timeout(400)
    check('restablecer quita el ajuste de Móvil y vuelve a heredar', fila('font-size') == 'diseno' and tam() != '30px', [fila('font-size'), tam()])
    pg.fill('#ad-font-size', '32px'); pg.press('#ad-font-size', 'Enter'); pg.wait_for_timeout(400)

    print('4. Columnas y orden por rango')
    COL = "c.parent() && tieneClase(c.parent(), 'row') && tieneClase(c, 'col-lg-4')"
    ed.sel(COL, 1)
    check('en una columna aparece «Ancho en la fila»', fila('columnas') is not None)
    pg.select_option('#ad-columnas', '12'); pg.wait_for_timeout(400)
    ancho_col = lambda: E(f"{ed.comp(COL, 1)}.getEl().getBoundingClientRect().width / {ed.comp(COL, 1)}.getEl().parentElement.getBoundingClientRect().width")
    check('en Móvil la columna ocupa toda la fila', fila('columnas') == 'local' and ancho_col() > 0.95, [fila('columnas'), ancho_col()])
    pg.select_option('#ad-order', '-1'); pg.wait_for_timeout(400)
    check('y se puede poner primera solo en Móvil', E(f"getComputedStyle({ed.comp(COL, 1)}.getEl()).order") == '-1')
    pg.click('[data-device=desktop]'); pg.wait_for_timeout(700); ed.sel(COL, 1)
    check('en Escritorio la columna conserva su ancho y su orden', E(f"getComputedStyle({ed.comp(COL, 1)}.getEl()).order") == '0' and ancho_col() < 0.6, ancho_col())

    print('5. Se conservan las reglas existentes')
    css_despues = E("editor.getCss()")
    viejas = [r.strip() for r in re.findall(r'[^{}]+\{[^{}]*\}', css_antes) if r.strip()]
    check('todas las reglas de antes siguen en el CSS', all(r in css_despues for r in viejas), [r for r in viejas if r not in css_despues][:3])
    check('solo se añadieron reglas (ninguna se perdió)', E("editor.Css.getRules().length") >= reglas_antes)

    print('6. Paneles plegables')
    an0 = E("document.querySelector('#gjs').clientWidth")
    z0 = E("editor.Canvas.getZoom()")
    pg.click('#btn-panel-izq'); pg.wait_for_timeout(500)
    check('plegar el panel izquierdo agranda el lienzo', E("document.querySelector('#gjs').clientWidth") > an0 + 200 and not pg.is_visible('#panel-izq'))
    pg.keyboard.press('Control+]'); pg.wait_for_timeout(500)
    check('Ctrl+] pliega el derecho', not pg.is_visible('#panel-der'))
    check('con más espacio, el escritorio se ve a mayor escala', E("editor.Canvas.getZoom()") > z0, [z0, E("editor.Canvas.getZoom()")])
    pg.click('#btn-panel-izq'); pg.keyboard.press('Control+]'); pg.wait_for_timeout(500)
    check('se vuelven a desplegar', pg.is_visible('#panel-izq') and pg.is_visible('#panel-der'))

    print('7. Guardar y reabrir')
    E("(editor.store(), 1)"); pg.wait_for_timeout(1500)
    pg.reload(); ed.esperar(); E("editor.Modal.close()")
    pg.click('[data-device=mobile]'); pg.wait_for_timeout(800)
    check('tras recargar, el hero sigue con 32 px solo en móvil', tam() == '32px', tam())
    pg.click('[data-device=desktop]'); pg.wait_for_timeout(800)
    check('y en escritorio sigue igual', tam() == tam_esc, [tam(), tam_esc])
    check('sin errores de JavaScript', not ed.errores, ed.errores[:3])
    b.close()
sys.exit(0 if resumen() else 1)
