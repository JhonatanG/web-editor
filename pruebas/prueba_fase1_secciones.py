"""Fase 1: secciones visuales y componentes vinculados.
Comprueba en Chrome: el panel Secciones (miniaturas con la identidad del sitio),
insertar antes/después/al final y arrastrando, deshacer en un paso, menú
vinculado que se cambia una sola vez, sobrescribir y volver a heredar, y la
migración segura de proyectos con menús distintos por página."""
import sys
from playwright.sync_api import sync_playwright
from comun import Editor, check, resumen

NAV = "ES_NAV(c)"
with sync_playwright() as p:
    b = p.chromium.launch(channel='chrome')
    ctx = b.new_context(viewport={'width': 1600, 'height': 950})
    ed = Editor(ctx)
    pg, E, V = ed.pg, ed.E, ed.V
    ed.empezar_de_cero()

    print('1. Panel Secciones')
    check('Secciones es la pestaña activa al abrir', E("document.querySelector('.tabs[data-group=left] button.active').dataset.tab") == 'secciones')
    cats = V("return [...document.querySelectorAll('#secciones .sec-cat')].map(g => g.dataset.cat)")
    check('categorías hero, servicios, portafolio, testimonios, faq y contacto', all(c in cats for c in ['hero', 'servicios', 'portafolio', 'testimonios', 'faq', 'contacto']), cats)
    pg.wait_for_timeout(1500)
    check('las miniaturas usan los colores del proyecto', E("[...document.querySelectorAll('#secciones .sec-mini iframe')].some(f => f.contentDocument && f.contentDocument.getElementById('tema').textContent.includes(TEMA.primario))"))
    pg.click('[data-tab=sitio]'); pg.fill('#t-primario-x', '#c2255c'); pg.press('#t-primario-x', 'Enter'); pg.wait_for_timeout(500)
    check('al cambiar la identidad, las miniaturas se repintan', E("[...document.querySelectorAll('#secciones .sec-mini iframe')].filter(f => f.contentDocument && f.contentDocument.getElementById('tema')).every(f => f.contentDocument.getElementById('tema').textContent.includes('#c2255c'))"))
    pg.click('[data-tab=blocks]')
    vis = V("return [...document.querySelectorAll('#blocks .gjs-block')].filter(b => b.offsetParent).map(b => b.textContent.trim())")
    check('Bloques conserva los estructurales (contenedor, fila, columnas)', all(any(x in v for v in vis) for x in ['Contenedor', 'Fila', '2 columnas']), vis[:8])
    check('las secciones completas ya no se repiten en Bloques', not any('Hero con video' in v or 'Portafolio' in v for v in vis))
    pg.click('[data-tab=secciones]')

    print('2. Insertar secciones')
    pg.click('.sec-card[data-sec="s-nav"] .sec-ins'); pg.wait_for_timeout(400)
    pg.click('.sec-card[data-sec="s-hero-img"] .sec-ins'); pg.wait_for_timeout(400)
    E("editor.select(null)"); pg.wait_for_timeout(200)
    pg.click('.sec-card[data-sec="sec-servicios-iconos"] .sec-ins'); pg.wait_for_timeout(400)
    E("editor.select(null)"); pg.wait_for_timeout(200)
    orden = lambda: V("const m = editor.getWrapper().components().find(c => tagDe(c) === 'main'); return m ? m.components().map(c => (c.getAttributes().id || c.getClasses().join('.'))) : []")
    check('el menú va al <header> y las secciones a <main>', E("tagDe(ES_NAV && buscarComp(editor.getWrapper(), ES_NAV)[0].parent()) === 'header'") and orden() == ['inicio', 'servicios'], orden())
    antes_html = E("editor.getHtml()")
    grupos0 = E("editor.UndoManager.getStackGroup().length")
    pg.click('.sec-card[data-sec="s-contacto"] .sec-ins'); pg.wait_for_timeout(500)
    check('contacto añadido al final', orden()[-1] == 'contacto', orden())
    check('la inserción es un solo paso del historial', E("editor.UndoManager.getStackGroup().length") == grupos0 + 1, [grupos0, E("editor.UndoManager.getStackGroup().length")])
    pg.click('#btn-undo'); pg.wait_for_timeout(400)
    check('un Ctrl+Z quita la sección entera y deja la página como estaba', E("editor.getHtml()") == antes_html and orden() == ['inicio', 'servicios'], orden())
    pg.click('#btn-redo'); pg.wait_for_timeout(400)
    check('rehacer la vuelve a poner', orden() == ['inicio', 'servicios', 'contacto'], orden())
    # Después de la sección seleccionada
    ed.sel("(c.getAttributes().id || '') === 'inicio'")
    check('con una sección elegida, el destino pasa a «después de»', E("document.querySelector('#sec-destino input[value=despues]').checked"))
    pg.click('.sec-card[data-sec="sec-portafolio"] .sec-ins'); pg.wait_for_timeout(400)
    check('portafolio queda justo después del hero', orden()[:3] == ['inicio', 'portafolio', 'servicios'], orden())
    check('lo insertado queda seleccionado', E("(editor.getSelected().getAttributes().id || '') === 'portafolio'"))
    # Antes de la sección seleccionada, eligiendo un elemento de dentro
    ed.sel("tagDe(c) === 'h2' && (seccionDe(c).getAttributes().id || '') === 'servicios'")
    pg.check('#sec-destino input[value=antes]')
    pg.click('.sec-card[data-sec="s-testimonios"] .sec-ins'); pg.wait_for_timeout(400)
    check('testimonios queda antes de servicios (aunque se eligió su título)', orden() == ['inicio', 'portafolio', 'testimonios', 'servicios', 'contacto'], orden())
    # Con el teclado: Enter sobre una tarjeta inserta en el destino elegido
    E("editor.select(null)"); pg.wait_for_timeout(200)
    pg.focus('.sec-card[data-sec="sec-faq"]'); pg.keyboard.press('Enter'); pg.wait_for_timeout(400)
    check('Enter sobre una tarjeta la inserta (al final)', orden()[-1] == 'preguntas', orden())
    # Vista previa grande con la identidad del sitio
    pg.click('.sec-card[data-sec="sec-cta"] .sec-ver'); pg.wait_for_timeout(800)
    check('la vista previa usa los colores del proyecto', E("document.querySelector('.sec-previa iframe').contentDocument.getElementById('tema').textContent.includes('#c2255c')"))
    pg.click('.sec-previa [data-ancho="390"]'); pg.wait_for_timeout(200)
    check('la vista previa cambia a ancho móvil', E("document.querySelector('.sec-previa iframe').style.width") == '390px')
    E("editor.Modal.close()")
    # Arrastrar al punto elegido del lienzo
    E("editor.select(null)")
    E("editor.Canvas.getDocument().getElementById('servicios').scrollIntoView({block:'center', behavior:'instant'})")
    pg.wait_for_timeout(300)
    g0 = E("editor.UndoManager.getStackGroup().length")
    antes_drag = E("editor.getHtml()")
    card = pg.locator('.sec-card[data-sec="sec-cta"]'); card.scroll_into_view_if_needed()
    bb = card.bounding_box()
    x, y = V("const r = editor.Canvas.getDocument().getElementById('servicios').getBoundingClientRect(), f = editor.Canvas.getFrameEl().getBoundingClientRect(), z = editor.Canvas.getZoom() / 100; return [f.left + (r.left + 300) * z, f.top + (r.top + 10) * z]")
    pg.mouse.move(bb['x'] + 40, bb['y'] + 30); pg.mouse.down()
    for i in range(1, 16):
        pg.mouse.move(bb['x'] + 40 + (x - bb['x'] - 40) * i / 15, bb['y'] + 30 + (y - bb['y'] - 30) * i / 15); pg.wait_for_timeout(40)
    pg.wait_for_timeout(300); pg.mouse.up(); pg.wait_for_timeout(900)
    o = orden()
    check('arrastrar una sección la coloca en el punto elegido (antes de servicios)', len(o) == 7 and o[o.index('servicios') - 1].startswith('seccion-cta'), o)
    check('arrastrar también es un solo paso del historial', E("editor.UndoManager.getStackGroup().length") == g0 + 1, [g0, E("editor.UndoManager.getStackGroup().length")])
    pg.click('#btn-undo'); pg.wait_for_timeout(400)
    check('y un Ctrl+Z la quita', E("editor.getHtml()") == antes_drag, orden())
    pg.click('#btn-redo'); pg.wait_for_timeout(400)

    print('3. Menú vinculado en varias páginas')
    for nombre in ('Servicios', 'Portafolio', 'Contacto'):
        ed.nueva_pagina(nombre)
    ed.ir_pagina(0)
    pg.click('[data-tab=pages]'); pg.click('#vinc-nav'); pg.wait_for_timeout(400)
    filas = V("return [...document.querySelectorAll('.vinc-fila')].map(f => [f.textContent.trim().replace(/\\s+/g,' '), f.querySelector('input').checked])")
    check('el asistente marca las páginas con el mismo menú', len(filas) == 3 and all(f[1] for f in filas), filas)
    pg.click('#vinc-ok'); pg.wait_for_timeout(600)
    check('el menú queda vinculado en las 4 páginas', E("piezasDe(vidDe(buscarComp(editor.getWrapper(), ES_NAV)[0])).length") == 4)
    check('Páginas muestra el estado vinculado', 'vinculado en 4' in pg.inner_text('#vinc-estado'), pg.inner_text('#vinc-estado'))
    # Cambiar el menú UNA vez (en el principal) y verlo en todas
    t = ed.escribir("tieneClase(c, 'nav-link')", 'Portada', 0)
    pg.wait_for_timeout(700)
    textos = V("return editor.Pages.getAll().map(p => buscarComp(p.getMainComponent(), c => tieneClase(c, 'nav-link'))[0].getInnerHTML().trim())")
    check('cambiar el menú una vez lo cambia en todas las páginas', t == 'Portada' and textos == ['Portada'] * 4, textos)
    E("(() => { const l = buscarComp(editor.getWrapper(), c => tieneClase(c, 'nav-link'))[1]; l.addAttributes({ href: 'servicios.html' }); return 1; })()")
    pg.wait_for_timeout(700)
    hrefs = V("return editor.Pages.getAll().map(p => buscarComp(p.getMainComponent(), c => tieneClase(c, 'nav-link'))[1].getAttributes().href)")
    check('un enlace cambiado en el principal llega a todas', hrefs == ['servicios.html'] * 4, hrefs)
    activos = V("return editor.Pages.getAll().map(p => buscarComp(p.getMainComponent(), c => tieneClase(c, 'nav-link') && tieneClase(c, 'active')).map(c => c.getAttributes().href))")
    check('cada página conserva su enlace activo', activos[0] == ['index.html'] and set(activos[1]) == {'servicios.html'} and activos[2] == [] and activos[3] == ['contacto.html'], activos)
    # Estilo del principal solo en móvil: llega a las instancias
    E("(() => { editor.select(buscarComp(editor.getWrapper(), c => tieneClase(c, 'navbar-brand'))[0]); return 1; })()")
    pg.click('[data-device=mobile]'); pg.wait_for_timeout(600)
    E("(() => { editor.getSelected().addStyle({ 'letter-spacing': '3px' }); return 1; })()")
    pg.wait_for_timeout(700)
    pg.click('[data-device=desktop]'); pg.wait_for_timeout(500)
    ed.ir_pagina(2)
    css = E("editor.getCss({ component: editor.Pages.getSelected().getMainComponent() })")
    check('el estilo de móvil del principal llega a la instancia (y solo en móvil)', '@media (max-width: 575px)' in css and 'letter-spacing:3px' in css.replace(' ', ''), css[-300:])
    # Instancia: sobrescribir el texto de la marca y volver a heredarlo
    check('en la instancia el panel lo identifica', True)
    ed.sel("tieneClase(c, 'navbar-brand')")
    check('caja «Instancia de…» visible', 'Instancia de' in pg.inner_text('#vinc-box'), pg.inner_text('#vinc-box'))
    check('la instancia no deja mover ni borrar sus piezas', E("(() => { const c = editor.getSelected(); return c.get('removable') === false && c.get('draggable') === false; })()"))
    t = ed.escribir("tieneClase(c, 'navbar-brand')", 'Portafolio Ana')
    pg.wait_for_timeout(400)
    ed.sel("tieneClase(c, 'navbar-brand')")
    check('el texto cambiado queda «propio de esta página»', t == 'Portafolio Ana' and 'propio de esta página' in pg.inner_text('#vinc-box'), pg.inner_text('#vinc-box'))
    ed.ir_pagina(0)
    ed.escribir("tieneClase(c, 'navbar-brand')", 'Estudio Norte')
    pg.wait_for_timeout(700)
    marcas = V("return editor.Pages.getAll().map(p => buscarComp(p.getMainComponent(), c => tieneClase(c, 'navbar-brand'))[0].getInnerHTML().trim())")
    check('el principal cambia la marca en todas menos donde se sobrescribió', marcas == ['Estudio Norte', 'Estudio Norte', 'Portafolio Ana', 'Estudio Norte'], marcas)
    ed.ir_pagina(2)
    ed.sel("tieneClase(c, 'navbar-brand')")
    pg.click('#vinc-box [data-rest="texto"]'); pg.wait_for_timeout(400)
    check('«volver a heredar» recupera el texto del principal', E(f"{ed.comp('tieneClase(c, \"navbar-brand\")')}.getInnerHTML().trim()") == 'Estudio Norte')
    pg.click('#vinc-box #vb-ir'); pg.wait_for_timeout(1500)
    check('«Editar el principal» lleva a su página', E("archivoDePagina(editor.Pages.getSelected())") == 'index.html')

    print('4. Guardar y reabrir conserva los vínculos')
    E("(editor.store(), 1)"); pg.wait_for_timeout(1500)
    pg.reload(); ed.esperar(); E("editor.Modal.close()")
    check('tras recargar sigue habiendo 1 principal y 3 instancias', V("const g = todosLosVinculos(); return g.length === 1 && !!g[0].principal && g[0].instancias.length === 3"))
    ed.escribir("tieneClase(c, 'nav-link')", 'Inicio', 0)
    pg.wait_for_timeout(700)
    check('y el vínculo sigue funcionando', V("return editor.Pages.getAll().every(p => buscarComp(p.getMainComponent(), c => tieneClase(c, 'nav-link'))[0].getInnerHTML().trim() === 'Inicio')"))

    print('5. Migración: menús distintos por página')
    # Un proyecto «antiguo»: dos páginas con el mismo menú y una con uno distinto
    E("(() => { todosLosVinculos().forEach(g => [g.principal, ...g.instancias].forEach(x => x && desvincular(x.comp))); return 1; })()")
    E("(() => { const l = buscarComp(editor.Pages.getAll()[3].getMainComponent(), c => tieneClase(c, 'nav-link'))[2]; l.components('Contáctanos ya'); return 1; })()")
    pg.click('[data-tab=pages]'); E("pintarEstadoVinculos()"); pg.wait_for_timeout(200)
    check('Páginas avisa que hay versiones distintas', 'versiones distintas' in pg.inner_text('#vinc-estado'), pg.inner_text('#vinc-estado'))
    pg.click('#vinc-nav'); pg.wait_for_timeout(400)
    filas = V("return [...document.querySelectorAll('.vinc-fila')].map(f => [f.className.split(' ').pop(), f.querySelector('input').checked])")
    check('la página distinta aparece sin marcar', filas == [['igual', True], ['igual', True], ['distinto', False]], filas)
    pg.click('#vinc-ok'); pg.wait_for_timeout(600)
    check('la página distinta conserva su menú', V("return buscarComp(editor.Pages.getAll()[3].getMainComponent(), c => tieneClase(c, 'nav-link'))[2].getInnerHTML().trim()") == 'Contáctanos ya')
    check('y no queda vinculada', V("return !vidDe(buscarComp(editor.Pages.getAll()[3].getMainComponent(), ES_NAV)[0])"))

    print('6. Tarjeta vinculada e inserción desde «Vinculados»')
    ed.sel("tieneClase(c, 'proyecto')")
    ed.respuestas.append('Tarjeta de proyecto')
    pg.click('#vb-crear'); pg.wait_for_timeout(400)
    pg.click('[data-tab=secciones]'); pg.wait_for_timeout(300)
    tarjeta = pg.locator('#sec-vinculados .sec-card', has_text='Tarjeta de proyecto')
    check('aparece en Secciones → Componentes vinculados (junto al menú)', tarjeta.count() == 1 and pg.locator('#sec-vinculados .sec-card').count() == 2)
    E("editor.select(null)")
    tarjeta.locator('.sec-ins').click(); pg.wait_for_timeout(500)
    check('se inserta una instancia vinculada', E("todosLosVinculos().find(g => g.principal.comp.get('vinculoNombre') === 'Tarjeta de proyecto').instancias.length") == 1)

    check('sin errores de JavaScript en el editor', not ed.errores, ed.errores[:3])
    b.close()
sys.exit(0 if resumen() else 1)
